/// A font of 8-pixel-wide glyphs: `height` bytes per glyph, top row first,
/// bit 7 leftmost.
#[derive(Clone, Copy)]
pub(super) struct Font<'a> {
    height: usize,
    glyphs: &'a [u8],
}

impl<'a> Font<'a> {
    /// A font of `glyphs.len() / height` glyphs; `None` unless `height` is
    /// 1 to 32 and `glyphs` holds whole glyphs.
    pub(super) fn new(height: usize, glyphs: &'a [u8]) -> Option<Self> {
        ((1..=32).contains(&height) && !glyphs.is_empty() && glyphs.len().is_multiple_of(height))
            .then_some(Self { height, glyphs })
    }

    pub(super) fn height(&self) -> usize {
        self.height
    }

    /// Row `y` of `glyph`; glyphs past the end of the font are blank.
    pub(super) fn row(&self, glyph: u8, y: usize) -> u8 {
        let at = usize::from(glyph) * self.height + y;
        self.glyphs.get(at).copied().unwrap_or(0)
    }
}

/// The VGA 80x25 text-mode font.
pub(super) const VGA_8X16: Font<'static> = Font {
    height: 16,
    glyphs: &VGA_8X16_GLYPHS,
};

