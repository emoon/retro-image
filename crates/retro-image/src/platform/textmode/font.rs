#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn built_in_glyphs_look_right() {
        // 'A' in the 8x16 font, and the full block in both.
        assert_eq!(VGA_8X16.row(b'A', 2), 0x10);
        assert_eq!(VGA_8X16.row(b'A', 7), 0xfe);
        assert!((0..16).all(|y| VGA_8X16.row(0xdb, y) == 0xff));
        assert!((0..8).all(|y| VGA_8X8.row(0xdb, y) == 0xff));
        assert_eq!(VGA_8X8.row(b' ', 3), 0);
    }

    #[test]
    fn new_validates_height_and_size() {
        assert!(Font::new(16, &[0; 4096]).is_some());
        assert!(Font::new(0, &[0; 4096]).is_none());
        assert!(Font::new(33, &[0; 33 * 256]).is_none());
        assert!(Font::new(16, &[0; 4095]).is_none());
        let small = Font::new(1, &[0xaa]).unwrap();
        assert_eq!((small.row(0, 0), small.row(1, 0)), (0xaa, 0));
    }
}
